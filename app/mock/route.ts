import { NextResponse } from "next/server"
import type { GeneratorData } from "@/types/generator"

/**
 * Helper to create a pool with label and values
 */
function pool(label: string, values: string[]) {
  return { label, values }
}

/**
 * Helper to create a modifier with attributes (4-level)
 */
function modifierWithAttrs(label: string, attributes: Record<string, ReturnType<typeof pool>>) {
  return { label, attributes }
}

/**
 * Helper to create a sub-type with pools
 */
function subType(label: string, pools: Record<string, ReturnType<typeof pool> | ReturnType<typeof modifierWithAttrs>>) {
  return { label, pools }
}

/**
 * Helper to create a category with sub-types
 */
function category(label: string, subTypes: Record<string, ReturnType<typeof subType>>) {
  return { label, subTypes }
}

